def cap(d): return 0.22 if d>=0.38 else 0.11

# build keep-intervals: speech + trimmed silence
keeps=[]; cur=0.0
for a,b in SIL:
    keeps.append((cur,a))                 # speech
    keeps.append((a, a+min(b-a,cap(b-a))))# trimmed pause
    cur=b
keeps.append((cur,END))
keeps=[(round(a,3),round(b,3)) for a,b in keeps if b-a>0.005]

# old->new time map
mapping=[]; t=0.0
for a,b in keeps:
    mapping.append((a,b,t)); t+=b-a
NEW=t
def remap(old):
    for a,b,n in mapping:
        if old<=b: return round(n+max(0,min(old,b)-a),3)
    return round(NEW,3)

json.dump({"keeps":keeps,"map":mapping,"new_dur":round(NEW,3)}, open("cutmap.json","w"))
